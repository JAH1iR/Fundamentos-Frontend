// operadores de asignación, incremento y decremento
let a = 1;
console.log('Valor inicial de a:', a);

a++; // aumenta el valor de a en 1
console.log('Después de a++:', a);

a += 5; // aumento variable
console.log('Después de a += 5:', a);

a--; // resta valor en 1
console.log('Después de a--:', a);

a -= 3; // resta variable
console.log('Después de a -= 3:', a);

a *= 5; // multiplica variable
console.log('Después de a *= 5:', a);

a /= 3; // divide variable
console.log('Después de a /= 3:', a);

a **= 2;
console.log('Después de a **= 2:', a);